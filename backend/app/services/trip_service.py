from __future__ import annotations

from datetime import date, datetime
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.models import (
    Trip,
    TripActivity,
    TripDay,
    TripRecommendation,
    TripVersion,
)
from app.schemas.trips import TripListItem, TripOut

PLACEHOLDER_TITLES = {"", "new trip", "untitled trip"}
TRIP_STATUSES = {"draft", "in_progress", "completed"}


def slugify(text: str) -> str:
    cleaned = "".join(c.lower() if c.isalnum() else "-" for c in text.strip())
    while "--" in cleaned:
        cleaned = cleaned.replace("--", "-")
    return cleaned.strip("-")[:200] or "trip"


def _to_date(value: Any) -> date | None:
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    try:
        return datetime.fromisoformat(str(value)).date()
    except ValueError:
        return None


def trip_full_query(trip_id: str):
    return (
        select(Trip)
        .where(Trip.id == trip_id)
        .options(
            selectinload(Trip.days).selectinload(TripDay.activities),
            selectinload(Trip.recommendations),
        )
        .execution_options(populate_existing=True)
    )


async def load_trip_full(db: AsyncSession, trip_id: str) -> Trip | None:
    return (await db.execute(trip_full_query(trip_id))).scalar_one_or_none()


def serialize_trip(trip: Trip) -> TripOut:
    out = TripOut.model_validate(trip)
    out.days.sort(key=lambda d: d.day_number)
    for d in out.days:
        d.activities.sort(key=lambda a: a.sort_order)
    return out


def serialize_trip_list_item(trip: Trip, day_count: int) -> TripListItem:
    item = TripListItem.model_validate(trip)
    item.day_count = day_count
    return item


def day_count_subquery():
    return (
        select(func.count(TripDay.id))
        .where(TripDay.trip_id == Trip.id)
        .correlate(Trip)
        .scalar_subquery()
    )


async def next_version_number(db: AsyncSession, trip_id: str) -> int:
    current = (
        await db.execute(select(func.max(TripVersion.version)).where(TripVersion.trip_id == trip_id))
    ).scalar_one_or_none()
    return int(current or 0) + 1


async def clear_plan(db: AsyncSession, trip_id: str) -> None:
    """Remove days/activities/recommendations so a plan can be re-applied (replan/restore)."""
    days = (
        await db.execute(
            select(TripDay).where(TripDay.trip_id == trip_id).options(selectinload(TripDay.activities))
        )
    ).scalars().all()
    for d in days:
        await db.delete(d)
    recs = (
        await db.execute(select(TripRecommendation).where(TripRecommendation.trip_id == trip_id))
    ).scalars().all()
    for r in recs:
        await db.delete(r)
    # Deletes must hit the DB before re-inserting rows with the same (trip_id, day_number)
    await db.flush()


async def apply_plan_to_trip(
    db: AsyncSession,
    trip: Trip,
    plan: dict[str, Any],
    *,
    prompt: str | None = None,
    change_summary: str = "Generated by TravelGraph agents",
    status: str = "completed",
    add_version: bool = True,
) -> Trip:
    """Write an aggregator `final_plan` onto a trip (fields, days, activities, recs, version)."""
    plan_title = str(plan.get("title") or "").strip()
    if (trip.title or "").strip().lower() in PLACEHOLDER_TITLES:
        trip.title = plan_title or trip.title or "New Trip"
    trip.plan_title = plan_title or trip.plan_title or ""
    trip.slug = slugify(trip.title)
    trip.destination = str(plan.get("destination") or trip.destination or "")
    trip.origin = str(plan.get("origin") or trip.origin or "")
    trip.travelers = int(plan.get("travelers") or trip.travelers or 2)
    trip.budget_inr = int(plan.get("budget_inr") or trip.budget_inr or 0)
    trip.estimated_cost_inr = int(plan.get("estimated_cost_inr") or 0)
    trip.budget_breakdown = plan.get("budget_breakdown") or {}
    trip.transport = plan.get("transport") or {}
    trip.accommodation = plan.get("accommodation") or {}
    cover = (plan.get("research") or {}).get("cover")
    trip.cover_image = cover or trip.cover_image or "/assets/destinations/generic.jpg"
    trip.status = status
    if prompt is not None:
        trip.prompt = prompt
    s, e = _to_date(plan.get("start_date")), _to_date(plan.get("end_date"))
    if s:
        trip.start_date = s
    if e:
        trip.end_date = e
    db.add(trip)
    await db.flush()

    await clear_plan(db, trip.id)

    for day in plan.get("days") or []:
        td = TripDay(
            trip_id=trip.id,
            day_number=int(day.get("day_number") or 0),
            title=day.get("title") or f"Day {day.get('day_number')}",
            summary=day.get("summary") or "",
            area=day.get("area") or "",
            image=day.get("image") or trip.cover_image,
            meta=day.get("meta") or {},
        )
        db.add(td)
        await db.flush()
        for i, act in enumerate(day.get("activities") or []):
            db.add(
                TripActivity(
                    day_id=td.id,
                    time_label=act.get("time_label") or "",
                    category=act.get("category") or "activity",
                    title=act.get("title") or "",
                    description=act.get("description") or "",
                    image=act.get("image") or "",
                    estimated_cost_inr=int(act.get("estimated_cost_inr") or 0),
                    sort_order=i,
                )
            )

    if plan.get("recommendation"):
        db.add(
            TripRecommendation(
                trip_id=trip.id,
                kind="ai",
                title="AI recommendation",
                body=str(plan["recommendation"]),
            )
        )
    for tip in plan.get("advisories") or []:
        db.add(TripRecommendation(trip_id=trip.id, kind="advisory", title="Travel note", body=str(tip)))

    if add_version:
        version = await next_version_number(db, trip.id)
        trip.current_version = version
        db.add(
            TripVersion(
                trip_id=trip.id,
                version=version,
                snapshot=plan,
                change_summary=change_summary[:255],
            )
        )
    await db.flush()
    return trip


async def duplicate_trip(db: AsyncSession, source: Trip) -> Trip:
    """Deep-copy a trip (days, activities, recommendations) as a fresh draft with version 1."""
    clone = Trip(
        user_id=source.user_id,
        title=f"{source.title} (copy)"[:200],
        slug=slugify(f"{source.title} copy"),
        plan_title=source.plan_title,
        destination=source.destination,
        origin=source.origin,
        start_date=source.start_date,
        end_date=source.end_date,
        travelers=source.travelers,
        budget_inr=source.budget_inr,
        estimated_cost_inr=source.estimated_cost_inr,
        status="draft",
        is_favorite=False,
        prompt=source.prompt,
        interests=list(source.interests or []),
        cover_image=source.cover_image,
        notes=source.notes,
        budget_breakdown=dict(source.budget_breakdown or {}),
        transport=dict(source.transport or {}),
        accommodation=dict(source.accommodation or {}),
        current_version=1,
    )
    db.add(clone)
    await db.flush()
    for d in sorted(source.days, key=lambda x: x.day_number):
        nd = TripDay(
            trip_id=clone.id,
            day_number=d.day_number,
            title=d.title,
            summary=d.summary,
            area=d.area,
            image=d.image,
            meta=dict(d.meta or {}),
        )
        db.add(nd)
        await db.flush()
        for a in sorted(d.activities, key=lambda x: x.sort_order):
            db.add(
                TripActivity(
                    day_id=nd.id,
                    time_label=a.time_label,
                    category=a.category,
                    title=a.title,
                    description=a.description,
                    image=a.image,
                    estimated_cost_inr=a.estimated_cost_inr,
                    sort_order=a.sort_order,
                )
            )
    for r in source.recommendations:
        db.add(TripRecommendation(trip_id=clone.id, kind=r.kind, title=r.title, body=r.body))
    db.add(
        TripVersion(
            trip_id=clone.id,
            version=1,
            snapshot=_snapshot_from_trip(source),
            change_summary=f"Duplicated from '{source.title}'"[:255],
        )
    )
    await db.flush()
    return clone


def _snapshot_from_trip(trip: Trip) -> dict[str, Any]:
    """Plan-shaped snapshot rebuilt from persisted rows (used when no run snapshot exists)."""
    return {
        "title": trip.plan_title or trip.title,
        "destination": trip.destination,
        "origin": trip.origin,
        "start_date": trip.start_date.isoformat() if trip.start_date else None,
        "end_date": trip.end_date.isoformat() if trip.end_date else None,
        "travelers": trip.travelers,
        "budget_inr": trip.budget_inr,
        "estimated_cost_inr": trip.estimated_cost_inr,
        "budget_breakdown": trip.budget_breakdown or {},
        "transport": trip.transport or {},
        "accommodation": trip.accommodation or {},
        "days": [
            {
                "day_number": d.day_number,
                "title": d.title,
                "summary": d.summary,
                "area": d.area,
                "meta": d.meta or {},
                "activities": [
                    {
                        "time_label": a.time_label,
                        "category": a.category,
                        "title": a.title,
                        "description": a.description,
                        "estimated_cost_inr": a.estimated_cost_inr,
                    }
                    for a in sorted(d.activities, key=lambda x: x.sort_order)
                ],
            }
            for d in sorted(trip.days, key=lambda x: x.day_number)
        ],
        "research": {"cover": trip.cover_image},
    }


def run_payload_from_trip(trip: Trip, overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "prompt": trip.prompt or f"Plan a trip to {trip.destination}",
        "destination": trip.destination,
        "origin": trip.origin,
        "start_date": trip.start_date.isoformat() if trip.start_date else None,
        "end_date": trip.end_date.isoformat() if trip.end_date else None,
        "travelers": trip.travelers,
        "budget_inr": trip.budget_inr,
        "interests": list(trip.interests or []),
    }
    for key, value in (overrides or {}).items():
        if value is not None:
            payload[key] = value
    return payload
